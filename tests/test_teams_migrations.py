@requires_postgres
def test_postgres_workspace_data_has_the_composite_key(empty_postgres):
    """`workspace_data` ends up keyed on (key, owner_id), under the name the
    migration's own downgrade expects to find."""
    cfg, url = empty_postgres

    command.upgrade(cfg, "head")

    engine = sa.create_engine(url)
    try:
        pk = sa.inspect(engine).get_pk_constraint("workspace_data")
    finally:
        engine.dispose()

    assert set(pk["constrained_columns"]) == {"key", "owner_id"}
    assert pk["name"] == "pk_workspace_data"


